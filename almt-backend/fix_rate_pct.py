def infer_rate(coa_name: str) -> tuple:
    """根据账户名称推断合理年化利率（%），返回 (rate_pct, comment)"""
    for pattern, rate_map, comment in RULES:
        if re.search(pattern, coa_name):
            dur = extract_dur(coa_name)
            if dur in rate_map:
                return rate_map[dur], f'{comment}（{dur}）'
            elif 'default' in rate_map:
                return rate_map['default'], f'{comment}（default 期限={dur or "无"}）'
            else:
                return None, f'{comment}（无匹配期限 {dur}）'
    return None, '无匹配规则'


def main():
    """从 argv[1] 或 stdin 读取 (coa_lvl, coa_name) 列表，生成 SQL"""
    if len(sys.argv) > 1 and sys.argv[1] != '-':
        with open(sys.argv[1], encoding='utf-8') as f:
            src = f.read()
    else:
        src = sys.stdin.read()

    updates = []  # (coa_lvl, rate_pct, comment)
    for line in src.strip().split('\n'):
        line = line.strip()
        if not line or line.startswith('+') or not line.startswith('|'):
            continue
        # MySQL -N -e 格式: coa_lvl\tcoa_name (但 grep 出来的带空格前缀)
        m = re.match(r'\|\s*(\S+)\s*\|\s*(\S[^|]*?)\s*\|', line)
        if not m:
            continue
        coa_lvl, coa_name = m.group(1).strip(), m.group(2).strip()
        rate_pct, comment = infer_rate(coa_name)
        updates.append((coa_lvl, rate_pct, coa_name, comment))

    # 生成 SQL
    print('-- 自动生成的真实利率修复 SQL')
    print('-- 基于央行基准利率 + LPR + SHIBOR 走廊（2024-2025）')
    print('-- 生成时间: 2026-09-15')
    print('-- 说明：NULL 表示不计息，0.00 表示名义零息')
    print()

    cnt = {'updated': 0, 'null': 0}
    for coa_lvl, rate_pct, coa_name, comment in updates:
        if rate_pct is None:
            print(f"-- NULL: {coa_lvl:<18} {coa_name:<40}  ({comment})")
            cnt['null'] += 1
        else:
            print(f"UPDATE almt_current_position SET rate_pct = {rate_pct/100:.6f} WHERE coa_lvl = '{coa_lvl}';  -- {coa_name} ({comment})")
            cnt['updated'] += 1

    print()
    print(f'-- 计划更新 {cnt["updated"]} 条利率记录，{cnt["null"]} 条置 NULL')


if __name__ == '__main__':
    main()
